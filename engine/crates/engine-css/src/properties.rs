/// The computed style of one element.
///
/// This is a plain struct of longhands with no heap indirection except `font_family`
/// and `content`, which is what the architecture specifies (§4 Stage 3) so a
/// restyle is a memcpy per node.
#[derive(Clone, Debug, PartialEq)]
pub struct ComputedStyle {
    // Box generation.
    pub display: Display,
    pub position: Position,
    pub float: Float,
    pub clear: Clear,
    pub overflow_x: Overflow,
    pub overflow_y: Overflow,
    pub z_index: i32,

    // Box model.
    pub width: Length,
    pub height: Length,
    pub min_width: Length,
    pub max_width: Length,
    pub min_height: Length,
    pub max_height: Length,
    pub margin: EdgeSizes,
    pub padding: EdgeSizes,
    pub border_widths: EdgeSizes,
    pub border_styles: [BorderStyle; 4],
    pub border_colors: [Rgba8; 4],
    pub border_radius: CornerRadii,

    // Positioning offsets.
    pub top: Length,
    pub right: Length,
    pub bottom: Length,
    pub left: Length,

    // Backgrounds and effects.
    pub background: Background,
    pub opacity: f32,

    // Text.
    pub color: Rgba8,
    pub font_size_px: f32,
    pub font_weight: u16,
    pub font_style: FontStyle,
    pub font_family: Vec<String>,
    pub line_height: LineHeight,
    pub letter_spacing: f32,
    pub text_align: TextAlign,
    pub text_decoration: TextDecoration,
    pub white_space: WhiteSpace,
    pub vertical_align: VerticalAlign,

    // Lists.
    pub list_style_type: ListStyleType,
    pub list_style_position: ListStylePosition,

    // Flex.
    pub flex_direction: FlexDirection,
    pub flex_wrap: FlexWrap,
    pub justify_content: JustifyContent,
    pub align_items: AlignItems,
    pub flex_grow: f32,
    pub flex_shrink: f32,
    pub flex_basis: Length,
    pub gap_row: Length,
    pub gap_column: Length,

    // Contents.
    pub content: Option<String>,

    // Table.
    pub table_layout: TableLayout,
    pub border_spacing: (Length, Length),

    // Inline.
    pub text_overflow: bool,
    pub cursor_pointer: bool,
    pub visibility_hidden: bool,
    pub box_sizing: BoxSizing,
}

