/// Whether a property inherits by default (§5.5).
///
/// This is a namespace of functions rather than a table keyed by `PropertyId`
/// because the agreed granularity is a struct: cascade code reads the field
/// directly, and adding a property means touching this module once.
pub mod inherit {
    use super::*;

    /// Copy the inherited fields from `parent` into `child`. Called once per
    /// node by the cascade before applying declarations, so a declaration with
    /// `inherit` just copies the parent's value for that field.
    pub fn apply_inherited(child: &mut ComputedStyle, parent: &ComputedStyle) {
        child.color = parent.color;
        child.font_size_px = parent.font_size_px;
        child.font_weight = parent.font_weight;
        child.font_style = parent.font_style;
        child.font_family = parent.font_family.clone();
        child.line_height = parent.line_height;
        child.letter_spacing = parent.letter_spacing;
        child.text_align = parent.text_align;
        child.white_space = parent.white_space;
        child.list_style_type = parent.list_style_type;
        child.list_style_position = parent.list_style_position;
        child.visibility_hidden = parent.visibility_hidden;
        child.cursor_pointer = parent.cursor_pointer;
        // `border-spacing` and `table-layout` inherit in CSS 2.1 tables.
        child.table_layout = parent.table_layout;
        child.border_spacing = parent.border_spacing;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn defaults_are_css_initials() {
        let s = ComputedStyle::default();
        assert_eq!(s.display, Display::Inline);
        assert_eq!(s.position, Position::Static);
        assert_eq!(s.font_size_px, 16.0);
        assert_eq!(s.color, Rgba8::BLACK);
        assert_eq!(s.opacity, 1.0);
        assert_eq!(s.font_weight, 400);
    }

    #[test]
    fn inherited_fields_copy() {
        let parent = ComputedStyle {
            color: Rgba8::rgb(1, 2, 3),
            font_size_px: 30.0,
            white_space: WhiteSpace::Pre,
            ..ComputedStyle::default()
        };
        let mut child = ComputedStyle::default();
        inherit::apply_inherited(&mut child, &parent);
        assert_eq!(child.color, parent.color);
        assert_eq!(child.font_size_px, 30.0);
        assert_eq!(child.white_space, WhiteSpace::Pre);
        // Non-inherited fields keep their initial values.
        assert_eq!(child.display, Display::Inline);
        assert_eq!(child.margin, EdgeSizes::ZERO);
    }

    #[test]
    fn overflow_clipping() {
        assert!(!Overflow::Visible.is_clipping());
        assert!(Overflow::Hidden.is_clipping());
        assert!(Overflow::Auto.is_clipping());
    }

    #[test]
    fn whitespace_predicates() {
        assert!(WhiteSpace::Pre.preserves_newlines());
        assert!(!WhiteSpace::Pre.collapses_spaces());
        assert!(!WhiteSpace::Nowrap.wraps());
        assert!(WhiteSpace::PreWrap.wraps());
    }
}