//! The longhand property set and the `ComputedStyle` struct.
//!
//! Everything the cascade produces is a *longhand*. Shorthands are expanded at
//! parse time (`shorthand.rs`), so the cascade has one declaration per property
//! and the winner is a simple max over (origin, importance, specificity, order).

use engine_core::{CornerRadii, EdgeSizes, Length, Rgba8};

/// `display` outer/inner pairs we support. `Grid` and `Table*` are parsed and
/// then lowered to `Block` by layout, with a report entry.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum Display {
    #[default]
    Inline,
    Block,
    InlineBlock,
    Flex,
    InlineFlex,
    Grid,
    InlineGrid,
    Table,
    TableRow,
    TableCell,
    ListItem,
    None,
    Contents,
}

impl Display {
    /// The box generated by this display value, ignoring the table stub.
    pub fn is_block_level(&self) -> bool {
        matches!(
            self,
            Display::Block | Display::Flex | Display::Grid | Display::Table | Display::ListItem
        )
    }

    pub fn is_inline_level(&self) -> bool {
        matches!(
            self,
            Display::Inline | Display::InlineBlock | Display::InlineFlex | Display::InlineGrid
        )
    }

    /// Lowering rule for stubs (§7.7/§7.8): grid and table boxes are laid out
    /// as blocks, and the report records the substitution.
    pub fn effective(&self) -> Display {
        match self {
            Display::Grid | Display::InlineGrid => Display::Grid,
            Display::Table => Display::Table,
            other => *other,
        }
    }
}

