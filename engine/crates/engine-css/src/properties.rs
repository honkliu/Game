#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum Overflow {
    #[default]
    Visible,
    Hidden,
    Scroll,
    Auto,
}

impl Overflow {
    /// Any non-`visible` overflow establishes a new block formatting context
    /// and clips its children.
    pub fn is_clipping(&self) -> bool {
        !matches!(self, Overflow::Visible)
    }
}

